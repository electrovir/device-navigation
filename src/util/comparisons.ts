/**
 * Just a wrapper for `>`.
 *
 * @category Internal
 */
export function greaterThan(a: any, b: any) {
    return a > b;
}

/**
 * Just a wrapper for `>`.
 *
 * @category Internal
 */
export function lessThan(a: any, b: any) {
    return a < b;
}
